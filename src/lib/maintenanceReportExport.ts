/**
 * The maintenance shift report as a file: PDF, TXT or Excel.
 *
 * All three are drawn from the one `ShiftReport` the builder returns — the same
 * completed orders, the same open orders, the same total counted downtime — so a PDF
 * sent to the manager and a TXT pasted into WhatsApp cannot say different things.
 * Nothing here reads the database or computes a figure; it only lays out what the
 * report already holds.
 *
 * The layout is the owner's brief of 01/11/2026: no database source names, no
 * "generated by", no planned/excluded/not-validated counters, no hand-over section,
 * no greetings. Completed orders carry their downtime large and bold; the total
 * counted downtime is the most prominent figure in the file.
 */
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import XLSX from "xlsx-js-style";
import {
  drawKpiCard, drawReportFooter, drawReportHeader, loadLogoDataUrl,
  HEADER_H, REPORT_MARGIN, tableStyles, NAVY, INK, SUBTLE, CARD_BG, CARD_BORDER,
} from "@/lib/reportTheme";
import {
  completedHeading, downtimeValue, laterStatusLabel, lineLabelOf, londonStamp, reportFileName, woRef,
  type ShiftReport,
} from "@/lib/maintenanceShiftReport";
import { formatMinutes } from "@/lib/formatDuration";

export type ReportFormat = "pdf" | "txt" | "xlsx";

const MIME: Record<ReportFormat, string> = {
  pdf: "application/pdf",
  txt: "text/plain;charset=utf-8",
  xlsx: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
};

const ddmmyyyy = (iso: string) => iso.split("-").reverse().join("/");
const clean = (s: string | null | undefined) => String(s ?? "").replace(/\s+/g, " ").trim();

export async function reportToFile(report: ShiftReport, format: ReportFormat): Promise<File> {
  const name = reportFileName(report.window, format);
  if (format === "txt") return new File([report.text], name, { type: MIME.txt });
  if (format === "xlsx") return new File([reportToXlsx(report)], name, { type: MIME.xlsx });
  return new File([await reportToPdf(report)], name, { type: MIME.pdf });
}

// ── Excel ─────────────────────────────────────────────────────────────────

export function reportToXlsx(r: ShiftReport): ArrayBuffer {
  const wb = XLSX.utils.book_new();
  const bold = { font: { bold: true } };
  const head = (cells: string[]) => cells.map((v) => ({ v, t: "s", s: { font: { bold: true, color: { rgb: "FFFFFF" } }, fill: { fgColor: { rgb: "1E3A8A" } } } }));

  const sum = XLSX.utils.aoa_to_sheet([
    [{ v: "Maintenance Report", t: "s", s: { font: { bold: true, sz: 14 } } }],
    [{ v: `${r.window.shift === "day" ? "Day" : "Night"} Shift · ${ddmmyyyy(r.window.sessionDate)}`, t: "s", s: bold }],
    [],
    [{ v: "Completed work orders", t: "s", s: bold }, r.completed.length],
    [{ v: "Downtime events", t: "s", s: bold }, r.downtimeEvents],
    [{ v: "Total counted downtime", t: "s", s: bold }, formatMinutes(r.totalCountedMinutes)],
    [{ v: "Open work orders", t: "s", s: bold }, r.open.length],
  ]);
  sum["!cols"] = [{ wch: 28 }, { wch: 40 }];
  XLSX.utils.book_append_sheet(wb, sum, "Summary");

  const done = XLSX.utils.aoa_to_sheet([
    head(["Line", "WO", "Machine", "Problem", "Work carried out", "Engineer", "Downtime"]),
    ...r.completed.map(({ wo, totalMinutes, work }) => [
      lineLabelOf(wo.line_at_time, wo.line_name), wo.wo_number ?? "",
      clean(wo.machine), clean(wo.description) || "Not recorded",
      work,
      clean(wo.engineer_name) || "Not assigned",
      formatMinutes(totalMinutes),
    ]),
  ]);
  done["!cols"] = [{ wch: 14 }, { wch: 8 }, { wch: 24 }, { wch: 36 }, { wch: 40 }, { wch: 18 }, { wch: 12 }];
  XLSX.utils.book_append_sheet(wb, done, "Completed");

  if (r.open.length) {
    const open = XLSX.utils.aoa_to_sheet([
      head(["WO", "Line", "Problem", "Engineer", "Status", "Downtime"]),
      ...r.open.map((p) => [
        p.wo_number ?? "", lineLabelOf(p.line_at_time, p.line_name), clean(p.description) || "Not recorded",
        clean(p.engineer_name) || "not assigned", "OPEN", downtimeValue(p),
      ]),
    ]);
    open["!cols"] = [{ wch: 8 }, { wch: 14 }, { wch: 40 }, { wch: 18 }, { wch: 10 }, { wch: 28 }];
    XLSX.utils.book_append_sheet(wb, open, "Open");
  }

  if (r.completedLater.length) {
    const later = XLSX.utils.aoa_to_sheet([
      head(["WO", "Line", "Problem", "Engineer", "Status", "Downtime"]),
      ...r.completedLater.map(({ wo, ...d }) => [
        wo.wo_number ?? "", lineLabelOf(wo.line_at_time, wo.line_name), clean(wo.description) || "Not recorded",
        clean(wo.engineer_name) || "Not assigned", laterStatusLabel(wo), downtimeValue(d),
      ]),
    ]);
    later["!cols"] = [{ wch: 8 }, { wch: 14 }, { wch: 40 }, { wch: 18 }, { wch: 28 }, { wch: 28 }];
    XLSX.utils.book_append_sheet(wb, later, "Completed later");
  }

  return XLSX.write(wb, { type: "array", bookType: "xlsx" });
}

// ── PDF ───────────────────────────────────────────────────────────────────

export async function reportToPdf(r: ShiftReport): Promise<ArrayBuffer> {
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const contentW = pageW - REPORT_MARGIN * 2;
  const logo = await loadLogoDataUrl();
  const subtitle = `${r.window.shift === "day" ? "Day" : "Night"} Shift · ${ddmmyyyy(r.window.sessionDate)}`;
  const generatedOn = londonStamp(r.generatedAt);
  const header = () => drawReportHeader(doc, { title: "Maintenance Report", subtitle, logo });
  header();

  let y = HEADER_H + 8;

  // ── Shift summary: two small figures, then the total downtime as the largest
  // thing on the page. ──
  const smallW = (contentW - 4) / 2;
  drawKpiCard(doc, { x: REPORT_MARGIN, y, w: smallW, h: 20, label: "Completed work orders", value: `${r.completed.length}` });
  drawKpiCard(doc, { x: REPORT_MARGIN + smallW + 4, y, w: smallW, h: 20, label: "Downtime events", value: `${r.downtimeEvents}` });
  y += 26;

  doc.setFillColor(...NAVY);
  doc.roundedRect(REPORT_MARGIN, y, contentW, 24, 2, 2, "F");
  doc.setFont("helvetica", "bold"); doc.setFontSize(8); doc.setTextColor(203, 213, 225);
  doc.text("TOTAL COUNTED DOWNTIME", REPORT_MARGIN + 6, y + 8);
  doc.setFontSize(24); doc.setTextColor(255, 255, 255);
  doc.text(formatMinutes(r.totalCountedMinutes), REPORT_MARGIN + 6, y + 19);
  y += 30;

  // ── Completed work orders: one block each, downtime large and bold. ──
  doc.setFont("helvetica", "bold"); doc.setFontSize(12); doc.setTextColor(...INK);
  doc.text("Completed work orders", REPORT_MARGIN, y + 4);
  y += 8;

  if (r.completed.length === 0) {
    doc.setFont("helvetica", "normal"); doc.setFontSize(9); doc.setTextColor(...SUBTLE);
    doc.text("No work orders were completed during this shift.", REPORT_MARGIN, y + 4);
    y += 8;
  }

  const field = (label: string, value: string, fy: number): number => {
    doc.setFont("helvetica", "bold"); doc.setFontSize(8); doc.setTextColor(...SUBTLE);
    doc.text(label, REPORT_MARGIN + 4, fy);
    doc.setFont("helvetica", "normal"); doc.setTextColor(...INK);
    const wrapped = doc.splitTextToSize(value, contentW - 44) as string[];
    doc.text(wrapped, REPORT_MARGIN + 40, fy);
    return fy + wrapped.length * 3.6 + 1.2;
  };

  for (const { wo, totalMinutes, work } of r.completed) {
    const rows: [string, string][] = [
      ...(clean(wo.machine) ? [["Machine", clean(wo.machine)] as [string, string]] : []),
      ["Problem", clean(wo.description) || "Not recorded"],
      ["Work carried out", work],
      ["Engineer", clean(wo.engineer_name) || "Not assigned"],
    ];
    // A translated note runs longer than the original; the card grows with its lines.
    doc.setFontSize(8);
    const fieldsH = rows.reduce((h, [, v]) => h + (doc.splitTextToSize(v, contentW - 44) as string[]).length * 3.6 + 1.2, 0);
    const blockH = 12 + fieldsH + 8;
    if (y + blockH > doc.internal.pageSize.getHeight() - 16) {
      doc.addPage(); header(); y = HEADER_H + 6;
    }
    doc.setFillColor(...CARD_BG); doc.setDrawColor(...CARD_BORDER);
    doc.roundedRect(REPORT_MARGIN, y, contentW, blockH, 2, 2, "FD");
    doc.setFillColor(...NAVY);
    doc.roundedRect(REPORT_MARGIN, y, 1.6, blockH, 0.8, 0.8, "F");

    doc.setFont("helvetica", "bold"); doc.setFontSize(10.5); doc.setTextColor(...INK);
    doc.text(completedHeading(wo), REPORT_MARGIN + 4, y + 6);

    let fy = y + 12;
    for (const [label, value] of rows) fy = field(label, value, fy);

    // The figure this report exists for.
    doc.setFont("helvetica", "bold"); doc.setFontSize(8); doc.setTextColor(...SUBTLE);
    doc.text("DOWNTIME", REPORT_MARGIN + 4, fy + 1);
    doc.setFontSize(15); doc.setTextColor(...NAVY);
    doc.text(formatMinutes(totalMinutes), REPORT_MARGIN + 40, fy + 2);
    y += blockH + 3;
  }

  // ── Open work orders: never counted as completed, listed as they stand. ──
  if (r.open.length) {
    if (y + 30 > doc.internal.pageSize.getHeight() - 16) {
      doc.addPage(); header(); y = HEADER_H + 6;
    }
    doc.setFont("helvetica", "bold"); doc.setFontSize(12); doc.setTextColor(...INK);
    doc.text("Open work orders", REPORT_MARGIN, y + 4);
    autoTable(doc, {
      startY: y + 7,
      head: [["WO", "Line", "Problem", "Engineer", "Status", "Downtime"]],
      body: r.open.map((p) => [
        p.wo_number ? `WO-${p.wo_number}` : "—",
        lineLabelOf(p.line_at_time, p.line_name),
        clean(p.description) || "Not recorded",
        clean(p.engineer_name) || "not assigned",
        "OPEN",
        downtimeValue(p),
      ]),
      ...tableStyles,
      margin: { top: HEADER_H + 6, left: REPORT_MARGIN, right: REPORT_MARGIN, bottom: 14 },
      didDrawPage: header,
    });
    y = (doc as any).lastAutoTable.finalY + 6;
  }

  // ── Stopped a line this shift, finished in another: without them the lists would
  // not add up to the total above. ──
  if (r.completedLater.length) {
    if (y + 30 > doc.internal.pageSize.getHeight() - 16) {
      doc.addPage(); header(); y = HEADER_H + 6;
    }
    doc.setFont("helvetica", "bold"); doc.setFontSize(12); doc.setTextColor(...INK);
    doc.text("Stopped this shift, completed later", REPORT_MARGIN, y + 4);
    autoTable(doc, {
      startY: y + 7,
      head: [["WO", "Line", "Problem", "Engineer", "Status", "Downtime"]],
      body: r.completedLater.map(({ wo, ...d }) => [
        woRef(wo.wo_number),
        lineLabelOf(wo.line_at_time, wo.line_name),
        clean(wo.description) || "Not recorded",
        clean(wo.engineer_name) || "Not assigned",
        laterStatusLabel(wo),
        downtimeValue(d),
      ]),
      ...tableStyles,
      margin: { top: HEADER_H + 6, left: REPORT_MARGIN, right: REPORT_MARGIN, bottom: 14 },
      didDrawPage: header,
    });
  }

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    drawReportFooter(doc, { pageNumber: i, generatedOn });
  }
  return doc.output("arraybuffer");
}
